/**
 * Get a contextual dialogue quote for a companion character
 */
export function getCompanionDialogue({
  charId,
  charName,
  isRunning = false,
  streak = 0,
  todayMinutes = 0,
  taskTitle = '',
}) {
  const pool = COMPANION_DIALOGUES[charId] || GENERIC_DIALOGUES;

  // Chance to say a contextual line based on real-time data
  const roll = Math.random();

  if (roll < 0.25 && streak >= 2) {
    if (charId === 'mochi') return `見事じゃ！${streak}日連続達成の道、このまま突き進むのじゃ！`;
    if (charId === 'shiba') return `連続${streak}日目だワン！この勢い、誰にも止められないワン！`;
    if (charId === 'calico') return `${streak}日連続で続いてるにゃ。実はすごいことにゃよ…！`;
    if (charId === 'slime') return `ぷるるん！${streak}日連続達成だぷる！ジャンプの勢い止まらないぷる！`;
    if (charId === 'hoshiusa') return `ぴょん★${streak}日連続達成！お星さまが特大に輝いてるぴょん！`;
    if (charId === 'kinoko') return `きのっ！${streak}日連続達成だきの！森の大木みたいに立派だきの！`;
    if (charId === 'ghostcat') return `ぽわ〜ん★${streak}日連続達成！嬉しくてフワフワ舞い上がっちゃうにゃ！`;
    if (charId === 'octopus') return `キュキュッ★${streak}日連続達成！ジェット全開で銀河記録更新だタコ！`;
    if (charId === 'robot') return `ピピピッ★${streak}日連続達成！ゼンマイフル回転で記録更新ロボ！`;
    return `連続記録${streak}日目！本当に素晴らしい継続力だよ！`;
  }

  if (roll < 0.45 && isRunning) {
    if (charId === 'mochi') return `今は集中タイムじゃ！${taskTitle ? `『${taskTitle}』に` : ''}全霊を注ぐがよい！`;
    if (charId === 'shiba') return `タイマー動いてるワン！オレも横で一緒に走るぜワン！`;
    if (charId === 'calico') return `集中タイムにゃね。お邪魔しないように見守ってるにゃ。`;
    if (charId === 'slime') return `ぷるっ！${taskTitle ? `『${taskTitle}』の` : ''}集中タイムだぷる！ピョンピョン応援するぷる！`;
    if (charId === 'hoshiusa') return `ぴょん！${taskTitle ? `『${taskTitle}』に` : ''}全力集中だぴょん！一緒にジャンプ★`;
    if (charId === 'kinoko') return `きのきの！${taskTitle ? `『${taskTitle}』に` : ''}全集中だきの！傘を広げて応援するきの！`;
    if (charId === 'ghostcat') return `ぽわっ！${taskTitle ? `『${taskTitle}』に` : ''}全集中タイムにゃ！そばで見守ってるにゃ★`;
    if (charId === 'octopus') return `ロケット点火！${taskTitle ? `『${taskTitle}』に` : ''}超光速集中だタコ！発進〜★`;
    if (charId === 'robot') return `タスク起動！${taskTitle ? `『${taskTitle}』の` : ''}集中プログラムを実行するロボ！`;
    return `今は全集中！一分一秒を大切に進めよう！`;
  }

  if (roll < 0.65 && todayMinutes >= 15) {
    if (charId === 'mochi') return `今日はすでに${todayMinutes}分も励んでおるな。大儀であった！`;
    if (charId === 'shiba') return `今日もう${todayMinutes}分も集中してるワン！凄すぎるワン！`;
    if (charId === 'calico') return `今日だけで${todayMinutes}分にゃ。かなり進んだにゃ〜！`;
    if (charId === 'slime') return `今日だけで${todayMinutes}分も！ぷるぷる感動したぷる〜！`;
    if (charId === 'hoshiusa') return `今日もう${todayMinutes}分も！お星さま満点の大活躍だぴょん★`;
    if (charId === 'kinoko') return `今日もう${todayMinutes}分も集中したきの！豊作大収穫だきの〜！`;
    if (charId === 'ghostcat') return `今日もう${todayMinutes}分も！おばけ級のすごい集中力だにゃ〜！`;
    if (charId === 'octopus') return `今日もう${todayMinutes}分も！宇宙飛行士級の素晴らしい集中力だタコ！`;
    if (charId === 'robot') return `今日もう${todayMinutes}分も稼働！驚異的な集中スペックだロボ！`;
    return `今日はすでに累計${todayMinutes}分集中！ナイスファイト！`;
  }

  // Pick a random personality line
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
